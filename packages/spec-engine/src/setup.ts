import { lstat, readFile, realpath } from 'node:fs/promises';
import { basename, join, resolve, sep } from 'node:path';
import { listTemplates, type RenderedTemplate, renderTemplate } from './templates.ts';

/**
 * Where Spectrum's installed pieces live in a client repository. The CLI writes these paths
 * and the dashboard reads them from a snapshot, so both use this one table.
 */
export const SETUP = {
  packageName: '@voyager-fm/spectrum',
  bin: 'spectrum',
  /** Repository-local binary that repository skills and the plugin prefer. */
  localBin: 'node_modules/.bin/spectrum',
  config: '.spectrum/config.json',
  skills: {
    claude: '.claude/skills/spectrum/SKILL.md',
    codex: '.agents/skills/spectrum/SKILL.md',
  },
  /** First words of the provenance comment in every installed skill file. */
  skillMarker: 'Generated by @voyager-fm/spectrum',
  claudeSettings: '.claude/settings.json',
  plugin: 'spectrum@spectrum',
  marketplace: 'voyager-fm/spectrum',
} as const;

export type SkillAgent = keyof typeof SETUP.skills;
export const SKILL_AGENTS = Object.keys(SETUP.skills) as SkillAgent[];

/** Commands a user runs in their repository. `--no` keeps npx from fetching another package. */
export const SETUP_COMMANDS = {
  install: `npm install --save-dev ${SETUP.packageName}`,
  init: `npx --no ${SETUP.bin} init`,
  skills: `npx --no ${SETUP.bin} skills install`,
  check: `npx --no ${SETUP.bin} check`,
  plugin: [
    `claude plugin marketplace add ${SETUP.marketplace}`,
    `claude plugin install ${SETUP.plugin}`,
  ],
} as const;

// Templates the starter bundle leaves out: optional tables need explicit configuration entries
// and engineering knowledge has no fixed authoring template.
const STARTER_EXCLUDED = /^(inventory\.(menus|custom)\.|engineering\.)/;

const STARTER_VALUES: Readonly<Record<string, string>> = {
  category_key: 'CORE',
  category_title: 'Core',
  feature_id: 'CORE-001',
  feature_title: 'First feature',
  interaction_id: 'CORE-001-first_interaction',
  interaction_title: 'First interaction',
  object_key: 'item',
  object_label: 'Item',
  surface_key: 'app',
  structure_key: 'app.main',
  region_label: 'Main',
  contract_id: 'core.first',
  initial_state: 'idle',
  result_state: 'done',
  read_state: 'item',
  write_state: 'item',
  page_id: 'HOME',
  page_key: 'home',
  page_title: 'Home',
  route_path: '/',
  page_contract_id: 'website.home',
};

/**
 * Render the connected starter bundle for a new repository. Every value Spectrum cannot know is
 * `TBD`, which the checker reports as a warning until a person decides it. Writes nothing.
 */
export async function renderStarterBundle(projectName: string): Promise<RenderedTemplate[]> {
  const name = projectName.trim();
  if (!name || /[\r\n\t\0]/.test(name)) throw new Error('Project name must be one line of text.');
  const templates = (await listTemplates()).filter(
    (template) => !STARTER_EXCLUDED.test(template.id),
  );
  const values: Record<string, string> = { ...STARTER_VALUES, project_name: name };
  const rendered: RenderedTemplate[] = [];
  for (const template of templates) {
    // Fill each value the template asks for that the starter does not decide.
    for (;;) {
      try {
        rendered.push(await renderTemplate(template.id, values));
        break;
      } catch (error) {
        const missing = /^Missing template value: (\w+)$/.exec((error as Error).message);
        if (!missing) throw error;
        values[missing[1]] = 'TBD';
      }
    }
  }
  // Engineering knowledge has no fixed template, but its configured root must exist.
  const config = rendered.find((file) => file.path === SETUP.config);
  const documents = config ? (JSON.parse(config.content).documents ?? []) : [];
  for (const document of documents as { kind?: string; root?: string }[]) {
    if (document.kind !== 'engineering' || !document.root) continue;
    const path = `${document.root}/README.md`;
    if (rendered.some((file) => file.path.startsWith(`${document.root}/`))) continue;
    rendered.push({
      path,
      content: [
        '# Engineering',
        '',
        'Architecture, implementation, standards and decision records for this repository.',
        'Add one Markdown article per topic with `doc_type`, `status` and',
        '`implementation_state` frontmatter. See the Spectrum schema guide for the format.',
        '',
      ].join('\n'),
    });
  }
  return rendered;
}

/** Default project name for a repository directory. */
export function defaultProjectName(root: string): string {
  return basename(resolve(root)) || 'Project';
}

export type SetupState = 'ok' | 'missing' | 'invalid' | 'unmanaged';
export interface SetupItem {
  state: SetupState;
  path: string;
  /** Short human-readable evidence, such as a version range or a parse problem. */
  detail: string | null;
}
export interface RepositorySetup {
  config: SetupItem;
  package: SetupItem;
  skills: Record<SkillAgent, SetupItem>;
  plugin: SetupItem;
}

const MAX_SETUP_FILE = 1024 * 1024;

/** Read a regular file inside root, or null. Symlinks and oversized files are never followed. */
async function readInside(root: string, path: string): Promise<string | null> {
  const target = join(root, path);
  try {
    const stat = await lstat(target);
    if (!stat.isFile() || stat.size > MAX_SETUP_FILE) return null;
    const [real, base] = await Promise.all([realpath(target), realpath(root)]);
    if (!real.startsWith(base + sep)) return null;
    return await readFile(target, 'utf8');
  } catch {
    return null;
  }
}

function parseJson(text: string): Record<string, unknown> | null {
  try {
    const value = JSON.parse(text);
    return value && typeof value === 'object' && !Array.isArray(value) ? value : null;
  } catch {
    return null;
  }
}

/** Version recorded in an installed skill's provenance comment, if present. */
export function skillVersion(content: string): string | null {
  const index = content.indexOf(SETUP.skillMarker);
  if (index < 0) return null;
  return /^ (\S+?);?\s/.exec(content.slice(index + SETUP.skillMarker.length))?.[1] ?? null;
}

/**
 * Report which Spectrum pieces a repository has, reading only fixed paths. Never throws and
 * never writes. Presence is declared setup, not proof that the pieces run.
 */
export async function inspectRepositorySetup(root: string): Promise<RepositorySetup> {
  const item = (path: string, state: SetupState, detail: string | null = null): SetupItem => ({
    state,
    path,
    detail,
  });

  const configText = await readInside(root, SETUP.config);
  const configJson = configText === null ? null : parseJson(configText);
  const config =
    configText === null
      ? item(SETUP.config, 'missing')
      : configJson?.schema_version === 2
        ? item(SETUP.config, 'ok', 'schema_version 2')
        : item(
            SETUP.config,
            'invalid',
            configJson ? 'schema_version is not 2' : 'not a JSON object',
          );

  const manifestText = await readInside(root, 'package.json');
  const manifest = manifestText === null ? null : parseJson(manifestText);
  let pkg: SetupItem;
  if (manifestText === null) pkg = item('package.json', 'missing', 'no package.json');
  else if (!manifest) pkg = item('package.json', 'invalid', 'not a JSON object');
  else {
    const range = (['devDependencies', 'dependencies'] as const)
      .map((field) => (manifest[field] as Record<string, unknown> | undefined)?.[SETUP.packageName])
      .find((value) => typeof value === 'string') as string | undefined;
    pkg = range
      ? item('package.json', 'ok', range)
      : item('package.json', 'missing', `${SETUP.packageName} is not declared`);
  }

  const skills = {} as Record<SkillAgent, SetupItem>;
  for (const agent of SKILL_AGENTS) {
    const path = SETUP.skills[agent];
    const content = await readInside(root, path);
    skills[agent] =
      content === null
        ? item(path, 'missing')
        : content.includes(SETUP.skillMarker)
          ? item(path, 'ok', skillVersion(content))
          : item(path, 'unmanaged', 'not installed by Spectrum');
  }

  const settingsText = await readInside(root, SETUP.claudeSettings);
  const settings = settingsText === null ? null : parseJson(settingsText);
  const enabled = (settings?.enabledPlugins as Record<string, unknown> | undefined)?.[SETUP.plugin];
  const plugin =
    settingsText === null
      ? item(SETUP.claudeSettings, 'missing')
      : !settings
        ? item(SETUP.claudeSettings, 'invalid', 'not a JSON object')
        : enabled === true
          ? item(SETUP.claudeSettings, 'ok', `${SETUP.plugin} enabled`)
          : item(SETUP.claudeSettings, 'missing', `${SETUP.plugin} is not enabled`);

  return { config, package: pkg, skills, plugin };
}
