import { readdir, readFile } from 'node:fs/promises';
import { join, relative, resolve } from 'node:path';
import { build, type Plugin } from 'esbuild';
import { VERSION } from './version.ts';

// Bundles the CLI into one self-contained Node script for the npm package and the plugin.
// Template files and the package version are embedded, so the bundle reads nothing from the
// workspace at run time.

const cliRoot = resolve(import.meta.dirname, '..');
const ENTRY = resolve(cliRoot, 'src/index.ts');
const TEMPLATES = resolve(cliRoot, '../../packages/spec-engine/templates');

async function templateFiles(directory = TEMPLATES): Promise<Record<string, string>> {
  const files: Record<string, string> = {};
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) Object.assign(files, await templateFiles(path));
    else if (entry.isFile() && entry.name !== 'README.md')
      files[relative(TEMPLATES, path).split('\\').join('/')] = await readFile(path, 'utf8');
  }
  return files;
}

function embed(files: Record<string, string>): Plugin {
  return {
    name: 'spectrum-embed',
    setup(build) {
      build.onLoad({ filter: /[\\/]spec-engine[\\/]src[\\/]template-files\.ts$/ }, () => ({
        loader: 'ts',
        contents: [
          `const files: Record<string, string> = ${JSON.stringify(files)};`,
          'export async function readTemplateFile(path: string): Promise<string> {',
          "  if (!Object.hasOwn(files, path)) throw new Error('Missing template file: ' + path);",
          '  return files[path];',
          '}',
        ].join('\n'),
      }));
      build.onLoad({ filter: /[\\/]cli[\\/]src[\\/]version\.ts$/ }, () => ({
        loader: 'ts',
        contents: `export const VERSION: string = ${JSON.stringify(VERSION)};`,
      }));
    },
  };
}

export async function bundleCli(generator: string): Promise<string> {
  const result = await build({
    entryPoints: [ENTRY],
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node20',
    write: false,
    legalComments: 'none',
    plugins: [embed(await templateFiles())],
    banner: {
      js: [
        '#!/usr/bin/env node',
        `// Generated by ${generator} from apps/cli. Do not edit.`,
        "import { createRequire as createRuntimeRequire } from 'node:module';",
        'const require = createRuntimeRequire(import.meta.url);',
      ].join('\n'),
    },
  });
  return result.outputFiles[0].text;
}
